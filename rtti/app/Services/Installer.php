<?php
declare(strict_types=1);

namespace App\Services;

use App\Core\DB;
use PDO;

final class Installer
{
    /** Split an SQL file into statements (quote-aware). */
    public static function splitSql(string $sql): array
    {
        $out = [];
        $buf = '';
        $len = strlen($sql);
        $q = null;
        for ($i = 0; $i < $len; $i++) {
            $c = $sql[$i];
            if ($q === null && $c === '-' && ($sql[$i + 1] ?? '') === '-') {
                $nl = strpos($sql, "\n", $i);
                $i = $nl === false ? $len : $nl;
                $buf .= "\n";
                continue;
            }
            if ($q !== null) {
                $buf .= $c;
                if ($c === '\\') {
                    $buf .= $sql[++$i] ?? '';
                } elseif ($c === $q) {
                    if (($sql[$i + 1] ?? '') === $q) {
                        $buf .= $sql[++$i];
                    } else {
                        $q = null;
                    }
                }
                continue;
            }
            if ($c === "'" || $c === '"' || $c === '`') {
                $q = $c;
                $buf .= $c;
                continue;
            }
            if ($c === ';') {
                if (trim($buf) !== '') {
                    $out[] = trim($buf);
                }
                $buf = '';
                continue;
            }
            $buf .= $c;
        }
        if (trim($buf) !== '') {
            $out[] = trim($buf);
        }
        return $out;
    }

    public static function runFile(PDO $pdo, string $file): void
    {
        foreach (self::splitSql((string)file_get_contents($file)) as $stmt) {
            $pdo->exec($stmt);
        }
    }

    /**
     * @param array $db  host, port, name, user, pass
     * @param array $opt admin_name, admin_user, admin_pass, admin_email, ho_name, ho_district, demo(bool)
     */
    public static function install(array $db, array $opt): array
    {
        $log = [];
        $dbName = $db['name'];
        if (!preg_match('/^[A-Za-z0-9_]+$/', $dbName)) {
            throw new \RuntimeException('Database name may contain only letters, numbers and underscore.');
        }
        $pdo = new PDO(sprintf('mysql:host=%s;port=%d;charset=utf8mb4', $db['host'], (int)$db['port']), $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
        $pdo->exec("CREATE DATABASE IF NOT EXISTS `$dbName` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
        $pdo->exec("USE `$dbName`");
        $existing = $pdo->query("SHOW TABLES LIKE 'users'")->fetchColumn();
        if ($existing) {
            throw new \RuntimeException("Database '$dbName' already contains RTTI tables. Use an empty database or drop it first.");
        }
        self::runFile($pdo, ROOT_PATH . '/database/schema.sql');
        $log[] = 'Schema created.';
        self::runFile($pdo, ROOT_PATH . '/database/seed.sql');
        $log[] = 'Reference data loaded.';

        // Write config
        $cfg = require ROOT_PATH . '/config/config.sample.php';
        $cfg['db'] = ['host' => $db['host'], 'port' => (int)$db['port'], 'name' => $dbName, 'user' => $db['user'], 'pass' => $db['pass'], 'charset' => 'utf8mb4'];
        if (!empty($opt['mysqldump'])) {
            $cfg['mysqldump'] = $opt['mysqldump'];
        }
        $php = "<?php\n// Generated by installer on " . date('Y-m-d H:i:s') . "\nreturn " . var_export($cfg, true) . ";\n";
        if (file_put_contents(ROOT_PATH . '/config/config.php', $php) === false) {
            throw new \RuntimeException('Could not write config/config.php – check folder permissions.');
        }
        $GLOBALS['__config'] = $cfg;
        $pdo->setAttribute(PDO::ATTR_DEFAULT_FETCH_MODE, PDO::FETCH_ASSOC);
        $pdo->setAttribute(PDO::ATTR_EMULATE_PREPARES, false);
        DB::setPdo($pdo);
        $log[] = 'config/config.php written.';

        PermissionSync::run(true);
        $log[] = 'Roles and permissions created.';

        $district = DB::row('SELECT id, division_id FROM districts WHERE name = :n', ['n' => $opt['ho_district'] ?: 'Rangpur'])
            ?? DB::row('SELECT id, division_id FROM districts ORDER BY id LIMIT 1');
        $hoId = DB::insert('centers', [
            'code' => 'HO', 'name' => $opt['ho_name'] ?: 'Head Office', 'is_head_office' => 1,
            'division_id' => $district['division_id'], 'district_id' => $district['id'], 'address' => $opt['ho_address'] ?? null,
        ]);
        DB::insert('accounts', ['name' => 'Head Office Cash', 'account_type' => 'cash', 'center_id' => $hoId]);

        $uid = DB::insert('users', [
            'name' => $opt['admin_name'] ?: 'System Administrator',
            'username' => $opt['admin_user'],
            'email' => $opt['admin_email'] ?: null,
            'password_hash' => password_hash($opt['admin_pass'], PASSWORD_DEFAULT),
            'default_center_id' => $hoId,
        ]);
        DB::query('INSERT INTO user_roles (user_id, role_id) SELECT :u, id FROM roles WHERE slug = "super_admin"', ['u' => $uid]);
        $log[] = "Super administrator '{$opt['admin_user']}' created.";

        if (!empty($opt['demo'])) {
            $log = array_merge($log, DemoData::load($uid, $hoId));
        }
        DB::query("INSERT INTO system_settings (setting_key, setting_value, setting_group) VALUES ('installed_at', :d, 'system')", ['d' => date('Y-m-d H:i:s')]);
        @file_put_contents(ROOT_PATH . '/storage/installed.lock', date('c'));
        return $log;
    }
}
